class Recipe < ApplicationRecord
  PHOTO_CONTENT_TYPES = %w[image/jpeg image/png image/webp].freeze
  PHOTO_MAX_BYTES = 10.megabytes
  MAX_TAGS = 10
  MAX_TAG_LENGTH = 30

  belongs_to :user
  has_one_attached :photo do |attachable|
    attachable.variant :thumb, resize_to_limit: [400, 400]
    attachable.variant :large, resize_to_limit: [1200, 1200]
  end
  # Lines are validated by ingredient_lines_are_valid, which reports errors by
  # position in the submitted list rather than in the association.
  has_many :recipe_ingredients, -> { order(:position) }, dependent: :destroy, autosave: true, validate: false
  has_many :ingredients, through: :recipe_ingredients

  enum :meal_type, %i[breakfast lunch dinner snack dessert appetizer side drink], validate: {allow_nil: true}
  enum :difficulty, %i[easy medium hard], validate: {allow_nil: true}
  enum :visibility, {public: 0, only_me: 1}, prefix: true, validate: true

  validates :title, presence: true, length: {maximum: 120}
  validates :description, length: {maximum: 2000}
  validates :servings, numericality: {only_integer: true, in: 1..100}
  validates :prep_minutes, :cook_minutes, numericality: {only_integer: true, greater_than_or_equal_to: 0}, allow_nil: true
  validate :steps_are_present_strings
  validate :ingredient_lines_are_valid
  validate :photo_is_an_acceptable_image
  validate :tags_are_valid

  normalizes :tags, with: ->(tags) { tags.map { |tag| tag.to_s.squish.downcase }.compact_blank.uniq }

  # The searchable column is generated by Postgres from title, description and
  # this copy of the ingredient names, which must be refreshed on every save.
  before_save :copy_ingredient_names

  # Recipes the user may view: their own, plus public recipes by active users
  # whose profile is public or who the user follows.
  scope :visible_to, ->(user) {
    visibility_public.where(user_id: User.content_visible_to(user).select(:id)).or(where(user: user))
  }

  # Public recipes by active users the user follows (not the user's own).
  scope :feed_for, ->(user) {
    visibility_public.where(user_id: user.follows_given.accepted.joins(:followed).merge(User.active).select(:followed_id))
  }

  # Full-text search over title, description and ingredient names. Accepts
  # web-search syntax: "quoted phrases", OR, and -excluded words.
  scope :search, ->(query) { where("recipes.searchable @@ websearch_to_tsquery('english', ?)", query) }
  scope :tagged_with_all, ->(tags) { where("recipes.tags @> ARRAY[?]::varchar[]", tags) }
  # Recipes with a known prep and/or cook time totalling at most `minutes`.
  scope :ready_within, ->(minutes) {
    where("(recipes.prep_minutes IS NOT NULL OR recipes.cook_minutes IS NOT NULL) AND " \
          "COALESCE(recipes.prep_minutes, 0) + COALESCE(recipes.cook_minutes, 0) <= ?", minutes)
  }

  def total_minutes
    (prep_minutes || 0) + (cook_minutes || 0) if prep_minutes || cook_minutes
  end

  # Replaces all ingredient lines. Each line is a hash with name, quantity, unit and note.
  def ingredient_lines=(lines)
    recipe_ingredients.each(&:mark_for_destruction)
    lines.each_with_index do |line, position|
      recipe_ingredients.build(
        ingredient_name: line[:name], quantity: line[:quantity], unit: line[:unit], note: line[:note], position: position
      )
    end
  end

  private

  def copy_ingredient_names
    self.ingredient_names = recipe_ingredients.reject(&:marked_for_destruction?).map(&:name).join(" ")
  end

  def tags_are_valid
    errors.add(:tags, "can't have more than #{MAX_TAGS} tags") if tags.size > MAX_TAGS
    errors.add(:tags, "must each be #{MAX_TAG_LENGTH} characters or fewer") if tags.any? { |tag| tag.length > MAX_TAG_LENGTH }
  end

  # Errors are keyed like "ingredients[1].unit", matching the API's ingredients param.
  def ingredient_lines_are_valid
    recipe_ingredients.reject(&:marked_for_destruction?).each_with_index do |line, index|
      next if line.valid?

      line.errors.each { |error| errors.add(:"ingredients[#{index}].#{error.attribute}", error.message) }
    end
  end

  def photo_is_an_acceptable_image
    return unless photo.attached?

    errors.add(:photo, "must be a JPEG, PNG or WebP image") unless photo.blob.content_type.in?(PHOTO_CONTENT_TYPES)
    errors.add(:photo, "must be 10 MB or smaller") if photo.blob.byte_size > PHOTO_MAX_BYTES
  end

  def steps_are_present_strings
    errors.add(:steps, "must be a list of non-blank text") unless steps.is_a?(Array) && steps.all?(&:present?)
  end
end
